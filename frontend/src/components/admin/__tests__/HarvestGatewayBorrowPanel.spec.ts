    mocks.get.mockResolvedValue({ ...value(), auto_quality: true, cookie_pool: { ...value().cookie_pool, enabled: true, models: ['gpt-6-astra', 'gpt-6.1-sol'], target_models: { '300': ['gpt-6.1-sol'] } } })
