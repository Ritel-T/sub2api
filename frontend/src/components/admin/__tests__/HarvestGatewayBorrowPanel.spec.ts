    expect(mocks.save).toHaveBeenLastCalledWith(expect.objectContaining({ cookie_pool: expect.objectContaining({ rotate_nodes: true, ip_affinity: true, max_node_attempts: 2, node_cooldown_seconds: 1800, source_account_ids: [299], target_account_ids: [300] }) }))
